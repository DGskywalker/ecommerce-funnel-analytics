# Canonical funnel. Every dataset maps onto these five steps; steps a dataset
# cannot observe are stored as NULL and skipped in the funnel maths.
STEPS = ["visit", "view", "cart", "checkout", "purchase"]

# The dimensions the dashboard can slice by (column name -> display label).
DIMENSIONS = {
    "channel": "Channel",
    "device": "Device",
    "region": "Region / country",
    "visitor_type": "Visitor type",
}


@dataclass(frozen=True)
class DatasetSpec:
    key: str
    name: str
    short: str
    is_real: bool
    has_revenue: bool
    time_grain: str  # "day" or "month"
    step_labels: dict[str, str | None]
    dim_labels: dict[str, str]
    source: str
    caveats: list[str] = field(default_factory=list)

    @property
    def observed_steps(self) -> list[str]:
        return [s for s in STEPS if self.step_labels.get(s)]

    def label(self, step: str) -> str:
        return self.step_labels.get(step) or step.title()


